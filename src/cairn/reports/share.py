"""`cairn share`: the built reports as one self-contained page, for single-file hosts such as
claude.ai artifacts.

The page holds every shared report, its text, figures (as data URIs), and Plotly figure
data; the sidebar switches between reports inside the page. Only Plotly's runtime is fetched, from a
public CDN at the exact version the build bundles. The page is published exactly as written: to change
it, edit reports/ and share again.
"""

from __future__ import annotations

import base64
import sys
import html
import json
import mimetypes
import re
from pathlib import Path

from . import build as builder
from ..config import Config
from ..term import hint, short_path, size as size_text

MAX_BYTES = 16 * 1024 * 1024  # claude.ai artifacts take at most 16 MB per page
PLOTLY_CDN = "https://cdn.jsdelivr.net/npm/plotly.js-dist-min@{version}/plotly.min.js"
URL_ATTRIBUTE = re.compile(r'(\s(?:src|data-src|href)=")([^"]+)(")')
NOTICE = (
    "<!-- Generated by cairn share from {source}. Publish this file exactly as written: do not edit,\n"
    "     restyle, split, or rewrite it. To change the report, edit {source} and run `cairn share` again. -->"
)


def share_dir(config: Config) -> Path:
    return config.output_dir.parent / "share"


def inline_assets(key: str, narrative: str, sizes: dict[str, int]) -> tuple[str, dict]:
    """Replace the report's own file URLs with data URIs; Plotly specs go into the bundle by URL."""
    folder = builder.output_dir(key).resolve()
    root = builder.OUTPUT_ROOT.resolve()
    files: dict[str, object] = {}

    def replace(match: re.Match) -> str:
        value = html.unescape(match.group(2))
        if re.match(r"^(?:[a-z][a-z0-9+.-]*:|#|/)", value, re.I):
            return match.group(0)
        path = (folder / value.split("#")[0].split("?")[0]).resolve()
        if root not in path.parents or not path.is_file():
            return match.group(0)  # a link to a report or an anchor: the page resolves it
        data = path.read_bytes()
        sizes[f"{key}: {value.split('?')[0]}"] = len(data)
        if path.suffix == ".json":
            files[value] = json.loads(data)
            return match.group(0)
        if path.suffix == ".svg":
            data = re.sub(rb"<!DOCTYPE[^>\[]*(\[[^\]]*\])?\s*>\s*", b"", data, count=1)  # hosts may refuse DTDs
        mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
        uri = f"data:{mime};base64,{base64.b64encode(data).decode()}"
        return f"{match.group(1)}{uri}{match.group(3)}"

    return URL_ATTRIBUTE.sub(replace, narrative), files


def script_json(value) -> str:
    """JSON safe inside a <script> element (and free of U+FFFD, which some hosts refuse)."""
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return text.replace("</", "<\\/").replace("<!--", "\\u003c!--").replace("\ufffd", "\\ufffd")


def page(title: str, notice: str, bundle: dict, start: str) -> str:
    shell = builder.page_file("index.html").read_text()
    body = shell.split("<body>", 1)[1].rsplit("</body>", 1)[0]
    body = re.sub(r'\s*<script src="[^"]*"></script>', "", body)
    sheets = [builder.page_file(name).read_text() for name in ("report.css", "report-extra.css")]
    sheets += [sheet.read_text() for sheet in (builder.CONFIG.extra_css if builder.CONFIG else ())]
    script = builder.page_file("report.js").read_text()
    if "</script" in script.lower() or any("</style" in sheet.lower() for sheet in sheets):
        raise SystemExit("cairn: report.js or a stylesheet contains </script or </style; it cannot be inlined")
    plotly = PLOTLY_CDN.format(version=builder.get_plotlyjs_version())
    return (
        f'{notice}\n<meta charset="utf-8">\n<title>{builder.esc(title)}</title>\n'
        + "".join(f"<style>\n{sheet}\n</style>\n" for sheet in sheets)
        + body.strip()
        + f'\n<script type="application/json" id="cairn-bundle">{script_json(bundle)}</script>\n'
        + f'<script data-plotly="{plotly}" data-report="{builder.esc(start)}">\n{script}\n</script>\n'
    )


def share(config: Config, report: str | None = None, build: bool = True, out: Path | None = None) -> Path:
    """Write the shared page for one report (`report`, a slug) or, by default, every report."""
    if build:
        builder.build_all(config)
    else:
        builder.configure(config)
    reports = builder.discover_reports()
    if report is not None and report.strip("/") not in reports:
        raise SystemExit(f"cairn: unknown report {report!r} (reports: {', '.join(reports)})")
    site = json.loads((builder.OUTPUT_ROOT / "site.json").read_text())
    wanted = [report.strip("/")] if report is not None else [entry["key"] for entry in site["reports"]]
    entries, bundle_reports, sizes = [], {}, {}
    for entry in site["reports"]:
        key = entry["key"]
        if key not in wanted:
            continue
        folder = builder.output_dir(key)
        if not (folder / "narrative.html").is_file():
            raise SystemExit(f"cairn: report {key} is not built\n" + hint("run `cairn build`", sys.stderr))
        narrative, files = inline_assets(key, (folder / "narrative.html").read_text(), sizes)
        data = json.loads((folder / "report-data.json").read_text())
        bundle_reports[key] = {"data": data, "narrative": narrative, "files": files}
        entries.append(entry)
    start = entries[0]["key"]
    title = bundle_reports[start]["data"]["title"] if report is not None else site["title"]
    bundle = {"start": start, "site": site | {"title": title, "reports": entries}, "reports": bundle_reports}
    source = (
        (builder.REPORTS_ROOT / start).relative_to(config.project).as_posix() + "/"
        if report is not None
        else builder.REPORTS_ROOT.relative_to(config.project).as_posix() + "/"
    )
    text = page(title, NOTICE.format(source=source), bundle, start)
    size = len(text.encode())
    if size > MAX_BYTES:
        largest = sorted(sizes.items(), key=lambda item: -item[1])[:8]
        shown = "\n  ".join(f"{name} ({count / 1e6:.1f} MB)" for name, count in largest)
        raise SystemExit(
            f"cairn: the shared page would be {size / 1e6:.1f} MB, above the {MAX_BYTES / 1e6:.0f} MB limit of single-file hosts\n"
            f"  share one report (--report) or make these figures smaller:\n  {shown}"
        )
    target = (out or share_dir(config) / "index.html").resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)
    names = ", ".join(bundle_reports)
    print(f"shared {short_path(target)} ({size_text(size)}; reports: {names})")
    print(hint("publish this one file unchanged (claude.ai: the Artifact tool, this file_path, no other files)"))
    print(hint("to change it, edit the report sources and run `cairn share` again"))
    return target
